function safeStorage() {
  try { return typeof localStorage === 'undefined' ? null : localStorage; } catch { return null; }
}

export function currentLang() {
  const stored = safeStorage()?.getItem(languageKey);
  return languages.some(item => item.code === stored) ? stored : 'ms';
}

export function currentTheme() {
  const stored = safeStorage()?.getItem(themeKey);
  return themes.some(item => item.code === stored) ? stored : 'blue';
}

